import numpy as np

def kmeans(clusterNum, data):
    print(f"クラスター数 {clusterNum}")

    clusterID = np.zeros(len(data))

    # 初期中心座標の設定
    #「データの最大インデックス(len(data)-1)」を「クラスター数-1」で割った数を増分幅とする
    step = (len(data) - 1) // (clusterNum - 1)
    center = np.empty((0, len(data[0])))

    # インデックス0（先頭要素）から最大インデックス未満の範囲で増分幅ごとにデータを抽出
    for idx in range(0, len(data), step):
        center = np.append(center, [data[idx]], axis=0)

        if len(center) == clusterNum:
            break

    print("初期値中心座標 : ", end="")
    print(*center)

    # 一つ前の中心座標を保持する配列
    pcenter = np.zeros((clusterNum, len(data[0])))

    # 中心座標が変化しなくなるまで繰り返す
    while True:
        # 各データと中心座標との最短距離の初期化
        clusterLen = np.full(len(data), float('inf'))

        for i in range(clusterNum):
            for j in range(len(data)):
                # ユークリッド距離の算出
                dist = np.linalg.norm(data[j] - center[i])
                if clusterLen[j] > dist:
                    clusterLen[j] = dist
                    clusterID[j] = i

        # 割り振られたクラスターIDに基づいて、各クラスターの中心座標を更新
        for i in range(clusterNum):
            tmp = []
            for j in range(len(data)):
                if clusterID[j] == i:
                    tmp.append(data[j])
            # 属するデータが1つ以上ある場合、平均値を新しい中心座標とする
            if len(tmp) != 0:
                c = np.array(tmp)
                center[i] = c.mean(axis=0)
            # 属するデータが0個の場合、データの範囲内でランダムに中心座標を再設定する
            else:
                center[i] =np.random.uniform(data.min(), data.max(), len(data[0]))

        # 一つ前の中心座標と現在の中心座標が完全に一致したら収束とみなしてループを終了
        if np.array_equal(pcenter, center):
            break

        # 計算過程で中心座標にNaN（非数）が含まれた場合の例外処理
        for i in range(clusterNum):
            if np.isnan(center[i]).any():
                center[i] = np.random.uniform(data.min(), data.max(), len(data[0]))

        # 現在の中心座標を「一つ前の中心座標」としてディープコピー
        pcenter = center.copy()

    # 収束後の最終結果をクラスターごとに出力する関数を呼び出す
    print_cluster(clusterNum, center, clusterID, data)
    print()

# クラスターIDごとに中心座標と密集度（コサイン類似度の平均）を算出・出力する関数
def print_cluster(clusterNum, center, clusterID, data):
    for i in range(clusterNum):
        # クラスターiに属するデータを抜き出すための空配列
        cn = np.empty((0, len(data[0])))
        cnn = []

        for j in range(len(data)):
            # クラスターIDが一致するデータを抽出
            if clusterID[j] == i:
                cn = np.append(cn, [data[j]], axis=0)
                # 中心座標とデータ間のコサイン類似度を計算してリストに追加
                cos_sim = np.dot(data[j], center[i]) / (np.linalg.norm(data[j]) * np.linalg.norm(center[i]))
                cnn.append(cos_sim)

        density = np.mean(cnn)

        print(f"クラスターID:{i}\t中心座標{center[i]}\t密集度{density}")


